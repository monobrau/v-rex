    $script:outputTextBox.BackColor = [System.Drawing.Color]::Black
    $script:outputTextBox.ForeColor = [System.Drawing.Color]::Lime
    $form.Controls.Add($script:outputTextBox)

    # Create GPO Button
    $createButton = New-Object System.Windows.Forms.Button
    $createButton.Location = New-Object System.Drawing.Point(550, 605)
    $createButton.Size = New-Object System.Drawing.Size(100, 30)
    $createButton.Text = "Create GPO"
    $createButton.BackColor = [System.Drawing.Color]::Green
    $createButton.ForeColor = [System.Drawing.Color]::White
    $createButton.Font = New-Object System.Drawing.Font("Segoe UI", 10, [System.Drawing.FontStyle]::Bold)
    $createButton.Add_Click({
        # Validate inputs
        if ([string]::IsNullOrWhiteSpace($gpoNameTextBox.Text)) {
            [System.Windows.Forms.MessageBox]::Show("Please enter a GPO name.", "Validation Error",
                [System.Windows.Forms.MessageBoxButtons]::OK, [System.Windows.Forms.MessageBoxIcon]::Warning)
            return
        }

        if ([string]::IsNullOrWhiteSpace($msiTextBox.Text)) {
            [System.Windows.Forms.MessageBox]::Show("Please select a Velociraptor MSI file.", "Validation Error",
                [System.Windows.Forms.MessageBoxButtons]::OK, [System.Windows.Forms.MessageBoxIcon]::Warning)
            return
        }

        if ([string]::IsNullOrWhiteSpace($serverTextBox.Text)) {
            [System.Windows.Forms.MessageBox]::Show("Please enter the Velociraptor server URL.", "Validation Error",
                [System.Windows.Forms.MessageBoxButtons]::OK, [System.Windows.Forms.MessageBoxIcon]::Warning)
            return
        }

        if ([string]::IsNullOrWhiteSpace($shareTextBox.Text)) {
            [System.Windows.Forms.MessageBox]::Show("Please enter a network share path.", "Validation Error",
                [System.Windows.Forms.MessageBoxButtons]::OK, [System.Windows.Forms.MessageBoxIcon]::Warning)
            return
        }

        $script:outputTextBox.Clear()
        Write-Log "=== Starting Velociraptor GPO Deployment ===" -Level Info

        New-VelociraptorGPO -GPOName $gpoNameTextBox.Text `
            -VelociraptorMSI $msiTextBox.Text `
            -ServerUrl $serverTextBox.Text `
            -NetworkShare $shareTextBox.Text `
            -TargetOU $ouComboBox.Text `
            -DeploymentMethod $methodComboBox.SelectedItem
    })
    $form.Controls.Add($createButton)

    # Close Button
    $closeButton = New-Object System.Windows.Forms.Button
    $closeButton.Location = New-Object System.Drawing.Point(660, 605)
    $closeButton.Size = New-Object System.Drawing.Size(100, 30)
    $closeButton.Text = "Close"
    $closeButton.Add_Click({ $form.Close() })
    $form.Controls.Add($closeButton)

    # Show initial log message
    Write-Log "V-Rex Velociraptor GPO Deployment Tool initialized" -Level Info
    Write-Log "Log file: $script:LogFile" -Level Info
    Write-Log "Ready to create GPO..." -Level Success

    # Show the form
    $form.Add_Shown({$form.Activate()})
    [void]$form.ShowDialog()
}

