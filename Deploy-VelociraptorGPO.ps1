# Logging function
function Write-Log {
    param(
        [string]$Message,
        [ValidateSet('Info', 'Warning', 'Error', 'Success')]
        [string]$Level = 'Info'
    )

    $timestamp = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
    $logMessage = "[$timestamp] [$Level] $Message"
    Add-Content -Path $script:LogFile -Value $logMessage

    # Also write to output textbox if available
    if ($script:outputTextBox) {
        $color = switch ($Level) {
            'Error' { [System.Drawing.Color]::Red }
            'Warning' { [System.Drawing.Color]::Orange }
            'Success' { [System.Drawing.Color]::Green }
            default { [System.Drawing.Color]::Black }
        }

        $script:outputTextBox.SelectionStart = $script:outputTextBox.TextLength
        $script:outputTextBox.SelectionLength = 0
        $script:outputTextBox.SelectionColor = $color
        $script:outputTextBox.AppendText("$logMessage`r`n")
        $script:outputTextBox.SelectionColor = $script:outputTextBox.ForeColor
        $script:outputTextBox.ScrollToCaret()
    }
}

# Function to validate Velociraptor MSI package
function Test-VelociraptorMSI {
    param(
        [string]$MsiPath
    )

    try {
        Write-Log "Validating Velociraptor MSI package..." -Level Info

        # Check if file exists
        if (!(Test-Path $MsiPath)) {
            Write-Log "MSI file not found: $MsiPath" -Level Error
            return $false
        }

        # Check file extension
        if ([System.IO.Path]::GetExtension($MsiPath) -ne ".msi") {
            Write-Log "File is not an MSI package: $MsiPath" -Level Error
            return $false
        }

        # Check file size (MSI should be at least 10MB with embedded config)
        $fileSize = (Get-Item $MsiPath).Length
        if ($fileSize -lt 10MB) {
            Write-Log "WARNING: MSI file size is unusually small ($([math]::Round($fileSize/1MB, 2)) MB)" -Level Warning
            Write-Log "This may indicate the MSI does not have embedded configuration." -Level Warning
            Write-Log "Make sure to use the MSI generated by Manage-VelociraptorServer.ps1" -Level Warning
        }

        # Check if file is accessible
        try {
            $stream = [System.IO.File]::OpenRead($MsiPath)
            $stream.Close()
        }
        catch {
            Write-Log "Cannot access MSI file: $($_.Exception.Message)" -Level Error
            return $false
        }

        Write-Log "MSI validation passed" -Level Success
        return $true
    }
    catch {
        Write-Log "MSI validation failed: $($_.Exception.Message)" -Level Error
        return $false
    }
}

