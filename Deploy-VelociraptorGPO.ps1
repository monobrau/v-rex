# Function to create the deployment script
function New-DeploymentScript {
    param(
        [string]$ScriptPath,
        [string]$VelociraptorMSI,
        [string]$ConfigFile,
        [string]$NetworkShare
    )

    $deployScript = @"
# Velociraptor Deployment Script
# Auto-generated by V-Rex GPO Deployment Tool

`$ErrorActionPreference = 'Stop'
`$LogFile = "$NetworkShare\Deployment\`$env:COMPUTERNAME-deployment.log"

function Write-DeployLog {
    param([string]`$Message)
    `$timestamp = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
    Add-Content -Path `$LogFile -Value "[`$timestamp] `$Message" -ErrorAction SilentlyContinue
}

try {
    Write-DeployLog "Starting Velociraptor deployment on `$env:COMPUTERNAME"

    # Create local directories
    `$installDir = "`$env:ProgramFiles\Velociraptor"
    `$configDir = "`$env:ProgramData\Velociraptor"

    if (!(Test-Path `$installDir)) {
        New-Item -Path `$installDir -ItemType Directory -Force | Out-Null
        Write-DeployLog "Created installation directory: `$installDir"
    }

    if (!(Test-Path `$configDir)) {
        New-Item -Path `$configDir -ItemType Directory -Force | Out-Null
        Write-DeployLog "Created configuration directory: `$configDir"
    }

    # IMPORTANT: Do NOT copy or create a custom client configuration file
    # The MSI package already contains the complete client configuration
    # including SSL certificates required for server authentication.
    # Overwriting this configuration will break client-server communication.
    #
    # The MSI installer will automatically place the embedded configuration
    # in the correct location during installation.

    Write-DeployLog "MSI contains embedded client configuration - no config copy needed"

    # Check if Velociraptor is already installed
    `$service = Get-Service -Name "Velociraptor" -ErrorAction SilentlyContinue

    if (`$service) {
        Write-DeployLog "Velociraptor service already exists. Checking version..."
        # You can add version checking logic here
    }
    else {
        Write-DeployLog "Installing Velociraptor from $VelociraptorMSI"

        # Install MSI silently
        `$arguments = "/i `"$VelociraptorMSI`" /quiet /norestart /log `"$NetworkShare\Deployment\`$env:COMPUTERNAME-install.log`""
        `$process = Start-Process -FilePath "msiexec.exe" -ArgumentList `$arguments -Wait -PassThru

        if (`$process.ExitCode -eq 0) {
            Write-DeployLog "Velociraptor installed successfully"
        }
        else {
            Write-DeployLog "ERROR: Installation failed with exit code `$(`$process.ExitCode)"
            exit `$process.ExitCode
        }
    }

    # Ensure network share directory exists for this computer
    `$computerShare = "$NetworkShare\`$env:COMPUTERNAME"
    if (!(Test-Path `$computerShare)) {
        New-Item -Path `$computerShare -ItemType Directory -Force | Out-Null
        Write-DeployLog "Created computer-specific evidence directory"
    }

    # Start the service if not running
    `$service = Get-Service -Name "Velociraptor" -ErrorAction SilentlyContinue
    if (`$service -and `$service.Status -ne 'Running') {
        Start-Service -Name "Velociraptor"
        Write-DeployLog "Started Velociraptor service"
    }

    Write-DeployLog "Velociraptor deployment completed successfully"
}
catch {
    Write-DeployLog "ERROR: `$(`$_.Exception.Message)"
    exit 1
}
"@

    try {
        $deployScript | Out-File -FilePath $ScriptPath -Encoding UTF8 -Force
        Write-Log "Created deployment script at $ScriptPath" -Level Success
        return $true
    }
    catch {
        Write-Log "Failed to create deployment script: $($_.Exception.Message)" -Level Error
        return $false
    }
}

# Function to create and configure GPO
function New-VelociraptorGPO {
    param(
        [string]$GPOName,
        [string]$VelociraptorMSI,
        [string]$ServerUrl,
        [string]$NetworkShare,
        [string]$TargetOU,
        [string]$DeploymentMethod
    )

    try {
        Write-Log "Starting GPO creation process..." -Level Info

        # Validate inputs
        if (!(Test-Path $VelociraptorMSI)) {
            throw "Velociraptor MSI file not found: $VelociraptorMSI"
        }

        # Test network share access
        if (!(Test-Path $NetworkShare)) {
            Write-Log "Creating network share directory: $NetworkShare" -Level Warning
            New-Item -Path $NetworkShare -ItemType Directory -Force | Out-Null
        }

        # Create subdirectories in network share
        $deploymentDir = Join-Path $NetworkShare "Deployment"

        if (!(Test-Path $deploymentDir)) {
            New-Item -Path $deploymentDir -ItemType Directory -Force | Out-Null
            Write-Log "Created directory: $deploymentDir" -Level Info
        }

        # Validate MSI package
        Write-Log "Validating Velociraptor MSI package..." -Level Info
        if (!(Test-VelociraptorMSI -MsiPath $VelociraptorMSI)) {
            throw "MSI validation failed. Please ensure you are using an MSI generated by Manage-VelociraptorServer.ps1"
        }

        # Display critical warning about MSI source
        Write-Log "IMPORTANT: The MSI must be generated using Manage-VelociraptorServer.ps1" -Level Warning
        Write-Log "Do NOT use generic Velociraptor MSIs from other sources" -Level Warning
        Write-Log "The MSI contains embedded SSL certificates required for client-server communication" -Level Info

        # NOTE: We do NOT create a client configuration file here.
        # The MSI generated by Manage-VelociraptorServer.ps1 already contains
        # the complete client configuration including SSL certificates.
        # Creating a separate config would overwrite these critical settings
        # and cause client-server connection failures.

        # Create deployment script (without config file parameter)
        $scriptFile = Join-Path $deploymentDir "Deploy-Velociraptor.ps1"
        if (!(New-DeploymentScript -ScriptPath $scriptFile -VelociraptorMSI $VelociraptorMSI -ConfigFile "" -NetworkShare $NetworkShare)) {
            throw "Failed to create deployment script"
        }

        # Check if GPO already exists
        $existingGPO = Get-GPO -Name $GPOName -ErrorAction SilentlyContinue
        if ($existingGPO) {
            $result = [System.Windows.Forms.MessageBox]::Show(
                "GPO '$GPOName' already exists. Do you want to overwrite it?",
                "GPO Exists",
                [System.Windows.Forms.MessageBoxButtons]::YesNo,
                [System.Windows.Forms.MessageBoxIcon]::Question
            )

            if ($result -eq [System.Windows.Forms.DialogResult]::No) {
                Write-Log "Operation cancelled by user" -Level Warning
                return $false
            }

            Write-Log "Using existing GPO: $GPOName" -Level Info
            $gpo = $existingGPO
        }
        else {
            # Create new GPO
            Write-Log "Creating new GPO: $GPOName" -Level Info
            $gpo = New-GPO -Name $GPOName -Comment "Velociraptor Forensic Agent Deployment - Created by V-Rex Tool"
            Write-Log "GPO created successfully: $($gpo.DisplayName)" -Level Success
        }

        # Configure GPO based on deployment method
        if ($DeploymentMethod -eq "Startup Script") {
            # Add startup script to GPO
            Write-Log "Configuring GPO with startup script..." -Level Info

            # Get the GPO path
            $gpoPath = "\\$env:USERDNSDOMAIN\SYSVOL\$env:USERDNSDOMAIN\Policies\{$($gpo.Id)}\Machine\Scripts\Startup"

            # Create the scripts directory if it doesn't exist
            if (!(Test-Path $gpoPath)) {
                New-Item -Path $gpoPath -ItemType Directory -Force | Out-Null
            }

            # Copy script to GPO path
            Copy-Item -Path $scriptFile -Destination $gpoPath -Force

            # Set the startup script using registry
            $key = "Software\Policies\Microsoft\Windows\System\Scripts\Startup\0"
            Set-GPRegistryValue -Name $GPOName -Key "HKLM\$key" -ValueName "Script" -Type String -Value "Deploy-Velociraptor.ps1"
            Set-GPRegistryValue -Name $GPOName -Key "HKLM\$key" -ValueName "Parameters" -Type String -Value ""
            Set-GPRegistryValue -Name $GPOName -Key "HKLM\$key" -ValueName "IsPowershell" -Type DWord -Value 1
            Set-GPRegistryValue -Name $GPOName -Key "HKLM\$key" -ValueName "ExecTime" -Type QWord -Value 0

            Write-Log "Startup script configured successfully" -Level Success
        }
        else {
            # Software Installation method
            Write-Log "Configuring GPO with software installation policy..." -Level Info

            # Copy MSI to a shared location accessible by all computers
            $gpoSoftwarePath = Join-Path $NetworkShare "Software"
            if (!(Test-Path $gpoSoftwarePath)) {
                New-Item -Path $gpoSoftwarePath -ItemType Directory -Force | Out-Null
            }

            $sharedMSI = Join-Path $gpoSoftwarePath (Split-Path $VelociraptorMSI -Leaf)
            Copy-Item -Path $VelociraptorMSI -Destination $sharedMSI -Force
            Write-Log "Copied MSI to shared location: $sharedMSI" -Level Info

            # Note: Software Installation via GPO requires GUI/COM objects which are complex in PowerShell
            # Instead, we'll use a startup script that handles the installation
            Write-Log "Note: Using startup script method for MSI deployment" -Level Warning
        }

        # Configure additional GPO settings
        Write-Log "Configuring additional GPO settings..." -Level Info

        # Enable PowerShell script execution if needed
        Set-GPRegistryValue -Name $GPOName -Key "HKLM\Software\Policies\Microsoft\Windows\PowerShell" `
            -ValueName "EnableScripts" -Type DWord -Value 1
        Set-GPRegistryValue -Name $GPOName -Key "HKLM\Software\Policies\Microsoft\Windows\PowerShell" `
            -ValueName "ExecutionPolicy" -Type String -Value "RemoteSigned"

        # Link GPO to OU if specified
        if ($TargetOU) {
            Write-Log "Linking GPO to OU: $TargetOU" -Level Info
            try {
                # Check if link already exists
                $existingLink = Get-GPInheritance -Target $TargetOU |
                    Select-Object -ExpandProperty GpoLinks |
                    Where-Object { $_.DisplayName -eq $GPOName }

                if (!$existingLink) {
                    New-GPLink -Name $GPOName -Target $TargetOU -LinkEnabled Yes
                    Write-Log "GPO linked successfully to $TargetOU" -Level Success
                }
                else {
                    Write-Log "GPO already linked to $TargetOU" -Level Info
                }
            }
            catch {
                Write-Log "Failed to link GPO to OU: $($_.Exception.Message)" -Level Error
            }
        }

        Write-Log "GPO creation and configuration completed successfully!" -Level Success
        Write-Log "GPO Name: $GPOName" -Level Info
        Write-Log "GPO ID: $($gpo.Id)" -Level Info
        Write-Log "MSI Package: $VelociraptorMSI" -Level Info
        Write-Log "Deployment script: $scriptFile" -Level Info
        Write-Log "Evidence will be stored in: $NetworkShare\<ComputerName>" -Level Info
        Write-Log "NOTE: Client configuration is embedded in the MSI - do not create custom configs!" -Level Warning

        [System.Windows.Forms.MessageBox]::Show(
            "GPO created successfully!`n`n" +
            "GPO Name: $GPOName`n" +
            "GPO ID: $($gpo.Id)`n`n" +
            "Evidence will be saved to: $NetworkShare\<ComputerName>`n`n" +
            "IMPORTANT: The MSI contains embedded client configuration.`n" +
            "Do not create or modify client config files manually.",
            "Success",
            [System.Windows.Forms.MessageBoxButtons]::OK,
            [System.Windows.Forms.MessageBoxIcon]::Information
        )

        return $true
    }
    catch {
        Write-Log "Error creating GPO: $($_.Exception.Message)" -Level Error
        [System.Windows.Forms.MessageBox]::Show(
            "Failed to create GPO: $($_.Exception.Message)",
            "Error",
            [System.Windows.Forms.MessageBoxButtons]::OK,
            [System.Windows.Forms.MessageBoxIcon]::Error
        )
        return $false
    }
}

# Function to browse for file
function Get-FilePath {
    param([string]$Filter = "MSI Files (*.msi)|*.msi|All Files (*.*)|*.*")

    $openFileDialog = New-Object System.Windows.Forms.OpenFileDialog
    $openFileDialog.Filter = $Filter
    $openFileDialog.Title = "Select Velociraptor MSI"

    if ($openFileDialog.ShowDialog() -eq [System.Windows.Forms.DialogResult]::OK) {
        return $openFileDialog.FileName
    }
    return $null
}

# Function to browse for folder
function Get-FolderPath {
    param([string]$Description = "Select Network Share for Evidence Storage")

    $folderBrowser = New-Object System.Windows.Forms.FolderBrowserDialog
    $folderBrowser.Description = $Description
    $folderBrowser.ShowNewFolderButton = $true

    if ($folderBrowser.ShowDialog() -eq [System.Windows.Forms.DialogResult]::OK) {
        return $folderBrowser.SelectedPath
    }
    return $null
}

# Function to get all OUs
function Get-OrganizationalUnits {
    try {
        Import-Module ActiveDirectory -ErrorAction Stop
        $ous = Get-ADOrganizationalUnit -Filter * | Select-Object -ExpandProperty DistinguishedName | Sort-Object
        return $ous
    }
    catch {
        Write-Log "Failed to retrieve OUs: $($_.Exception.Message)" -Level Warning
        return @()
    }
}

